#!/usr/bin/env python3
"""Render Scripts/cobra.pixels into the app icon and the menu bar glyph.

Pillow is not available here, so PNGs are encoded directly with zlib. The same
pixel map drives both outputs, which is the point: the icon in the Dock and the
glyph in the menu bar are the same drawing at different sizes.
"""
import pathlib
import struct
import subprocess
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PIXELS = ROOT / "Scripts" / "cobra.pixels"
BUILD = ROOT / "build"

BODY = (0x7C, 0xFF, 0x4F, 255)      # venom
TONGUE = (0xFF, 0x4F, 0x5E, 255)    # danger red
BACKDROP = (0x14, 0x14, 0x17, 255)  # surface
EMPTY = (0, 0, 0, 0)

# Proportion of the canvas the rounded tile occupies. macOS icons are not
# edge-to-edge; leaving a margin keeps Cobra visually the same size as its
# neighbours in the Dock.
TILE_SCALE = 0.82
CORNER_RATIO = 0.22


def load_map():
    rows = []
    for line in PIXELS.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        rows.append(line)
    width = max(len(r) for r in rows)
    return [r.ljust(width, ".") for r in rows], width, len(rows)


def write_png(path, width, height, pixels):
    """pixels: flat list of RGBA tuples, row-major."""
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # no per-row filter
        for x in range(width):
            raw.extend(pixels[y * width + x])

    def chunk(tag, data):
        body = struct.pack(">I", len(data)) + tag + data
        return body + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    blob = b"\x89PNG\r\n\x1a\n"
    blob += chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
    blob += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    blob += chunk(b"IEND", b"")
    path.write_bytes(blob)


def inside_rounded(x, y, left, top, size, radius):
    if not (left <= x < left + size and top <= y < top + size):
        return False
    dx = min(x - left, left + size - 1 - x)
    dy = min(y - top, top + size - 1 - y)
    if dx >= radius or dy >= radius:
        return True
    ox, oy = radius - dx, radius - dy
    return ox * ox + oy * oy <= radius * radius


def render(size, grid, gw, gh, backdrop=True):
    pixels = [EMPTY] * (size * size)

    tile = int(size * TILE_SCALE)
    left = (size - tile) // 2
    radius = max(1, int(tile * CORNER_RATIO))

    if backdrop:
        for y in range(size):
            for x in range(size):
                if inside_rounded(x, y, left, left, tile, radius):
                    pixels[y * size + x] = BACKDROP

    # Fit the pixel grid inside the tile, snapped to whole pixels so the art
    # stays crisp rather than resampled into mush.
    art = tile if backdrop else size
    scale = max(1, int(art * 0.78) // max(gw, gh))
    art_w, art_h = gw * scale, gh * scale
    ox = (size - art_w) // 2
    oy = (size - art_h) // 2

    colors = {"#": BODY, "~": TONGUE}
    for row in range(gh):
        for col in range(gw):
            color = colors.get(grid[row][col])
            if color is None:
                continue
            for dy in range(scale):
                for dx in range(scale):
                    x, y = ox + col * scale + dx, oy + row * scale + dy
                    if 0 <= x < size and 0 <= y < size:
                        pixels[y * size + x] = color
    return pixels


def make_icns(grid, gw, gh):
    iconset = BUILD / "Cobra.iconset"
    iconset.mkdir(parents=True, exist_ok=True)

    for base in (16, 32, 128, 256, 512):
        for factor, suffix in ((1, ""), (2, "@2x")):
            size = base * factor
            name = f"icon_{base}x{base}{suffix}.png"
            write_png(iconset / name, size, size, render(size, grid, gw, gh))

    icns = BUILD / "AppIcon.icns"
    subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(icns)], check=True)
    print(f"wrote {icns}")


def make_swift(grid):
    out = ROOT / "Sources" / "CobraMac" / "CobraPixels.swift"
    rows = ",\n".join(f'        "{row}"' for row in grid)
    out.write_text(
        "// Generated by Scripts/make-icon.py from Scripts/cobra.pixels.\n"
        "// Edit the pixel map, not this file.\n\n"
        "enum CobraPixels {\n"
        "    static let map: [String] = [\n"
        f"{rows},\n"
        "    ]\n"
        "}\n"
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    grid, gw, gh = load_map()
    BUILD.mkdir(exist_ok=True)
    make_icns(grid, gw, gh)
    make_swift(grid)
